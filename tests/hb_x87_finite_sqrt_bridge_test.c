static uint64_t calls, accepted, declined, checks, failures;
static uint64_t group_calls[GROUPS], category_failures[CATEGORIES];
static char phase[192] = "setup";
static int check(bool condition, const char *message, unsigned category) {
    ++checks;
    if (!condition) {
        ++failures; ++category_failures[category];
        if (failures <= 32) fprintf(stderr, "FAIL %s: %s\n", phase, message);
    }
    return condition;
}
static void encode(uint8_t raw[10], raw_t value) {
    for (unsigned i = 0; i < 8; ++i) raw[i] = (uint8_t)(value.sig >> (i * 8));
    raw[8] = (uint8_t)value.se; raw[9] = (uint8_t)(value.se >> 8);
}
static uint16_t control_word(unsigned pi, unsigned rc, unsigned pm) {
    static const unsigned pc[] = { 0, 2, 3 };
    return (uint16_t)(0x005fu | (pc[pi] << 8) | (rc << 10) | (pm << 5));
}
typedef struct { int rc, flags; uint64_t fpcr, fpsr; } host_t;
static host_t host_state(void) {
    host_t state = { .rc = fegetround(), .flags = fetestexcept(FE_ALL_EXCEPT), .fpcr = 0, .fpsr = 0 };
#if defined(__aarch64__) || defined(__arm64__)
    __asm__ __volatile__("mrs %0, fpcr" : "=r"(state.fpcr) :: "memory");
    __asm__ __volatile__("mrs %0, fpsr" : "=r"(state.fpsr) :: "memory");
#endif
    return state;
}
static bool same_host(host_t a, host_t b) {
    return a.rc == b.rc && a.flags == b.flags && a.fpcr == b.fpcr && a.fpsr == b.fpsr;
}
static int seed_host(unsigned host, unsigned flags) {
    static const int modes[] = { FE_TONEAREST, FE_DOWNWARD, FE_UPWARD, FE_TOWARDZERO };
    int wanted = flags ? FE_INVALID | FE_DIVBYZERO : 0;
    return check(fesetround(modes[host]) == 0 && feclearexcept(FE_ALL_EXCEPT) == 0 &&
                 (!wanted || feraiseexcept(wanted) == 0) &&
                 fegetround() == modes[host] && fetestexcept(FE_ALL_EXCEPT) == wanted,
                 "masked host RC/status installed", HOST);
}
typedef struct {
    uint8_t before[8];
    hb_x87_finite_result_t value;
    uint8_t after[8];
} guarded_output_t;

static void run_case(const char *name, raw_t input, const answer_t *answer,
                     unsigned pi, unsigned rc, unsigned pm, unsigned host,
                     unsigned host_flags, unsigned group, bool alias) {
    uint8_t source[26], source_before[26], expected_raw[10] = {0};
    guarded_output_t output, output_before;
    memset(source, 0x5a, sizeof(source)); memset(&output, 0xa5, sizeof(output));
    encode(source + 8, input); memcpy(source_before, source, sizeof(source));
    const uint8_t *operand = source + 8;
    if (alias) { encode(output.value.raw, input); operand = output.value.raw; }
    memcpy(&output_before, &output, sizeof(output));
    uint16_t cw = control_word(pi, rc, pm);
    if (group == RESERVED_GROUP) cw = (uint16_t)((cw & ~0x0300u) | 0x0100u);
    bool expected = answer && group != RESERVED_GROUP &&
                    (!(answer->status_bits & 0x0020u) || pm != 0);
    if (answer) encode(expected_raw, answer->raw);
    snprintf(phase, sizeof(phase), "%s PC=%u RC=%u PM=%u host=%u flags=%u group=%u alias=%u",
             name, (unsigned)((cw >> 8) & 3u), rc, pm, host, host_flags, group, (unsigned)alias);
    if (!seed_host(host, host_flags)) return;
    host_t before = host_state();
    bool result = hb_x87_finite_sqrt(operand, cw, &output.value);
    host_t after = host_state();
    ++calls; ++group_calls[group]; if (result) ++accepted; else ++declined;
    check(same_host(before, after), "host fenv and full ARM64 FPCR/FPSR unchanged", HOST);
    check(result == expected, "literal private-API admission", API);
    check(!memcmp(source, source_before, sizeof(source)), "independent raw input and canaries unchanged", STATE);
    check(!memcmp(output.before, output_before.before, sizeof(output.before)) &&
          !memcmp(output.after, output_before.after, sizeof(output.after)), "output exterior canaries unchanged", STATE);
    if (expected) {
        check(!memcmp(output.value.raw, expected_raw, sizeof(expected_raw)), "certified rounded raw80 result", NUMERIC);
        check(output.value.status_bits == answer->status_bits && !(output.value.status_bits & ~0x0220u),
              "literal PE/C1 metadata only", NUMERIC);
    } else {
        check(!memcmp(&output, &output_before, sizeof(output)), "false result preserves all output bytes", API);
    }
}
static void run_null(unsigned missing, unsigned ci, unsigned host, unsigned host_flags) {
    static const uint16_t controls[] = { 0x037f, 0x085f, 0x0d7f, 0x067f };
    const raw_t one = { 0x3fff, UINT64_C(0x8000000000000000) };
    uint8_t source[26], source_before[26];
    guarded_output_t output, output_before;
    memset(source, 0x5a, sizeof(source)); memset(&output, 0xa5, sizeof(output));
    encode(source + 8, one); memcpy(source_before, source, sizeof(source));
    memcpy(&output_before, &output, sizeof(output));
    snprintf(phase, sizeof(phase), "null missing=%u cw=%04x host=%u flags=%u",
             missing, (unsigned)controls[ci], host, host_flags);
    if (!seed_host(host, host_flags)) return;
    host_t before = host_state();
    bool result = hb_x87_finite_sqrt(missing == 0 || missing == 2 ? NULL : source + 8,
                                    controls[ci], missing == 1 || missing == 2 ? NULL : &output.value);
    host_t after = host_state();
    ++calls; ++group_calls[NULL_GROUP]; if (result) ++accepted; else ++declined;
    check(same_host(before, after), "null path preserves host fenv/FPCR/FPSR", HOST);
    check(!result, "null arguments decline", API);
    check(!memcmp(source, source_before, sizeof(source)), "null path preserves raw input and canaries", STATE);
    check(!memcmp(&output, &output_before, sizeof(output)), "null path preserves complete output and canaries", API);
}
int main(void) {
    host_t caller = host_state();
    fenv_t original;
    if (feholdexcept(&original) != 0) {
        fprintf(stderr, "Unable to save/mask caller floating-point environment\n");
        return 2;
    }
    for (unsigned host = 0; host < 4; ++host)
    for (unsigned hf = 0; hf < 2; ++hf) {
        for (unsigned pi = 0; pi < 3; ++pi)
        for (unsigned rc = 0; rc < 4; ++rc)
        for (unsigned pm = 0; pm < 2; ++pm) {
            for (size_t i = 0; i < sizeof(samples)/sizeof(samples[0]); ++i)
                run_case(samples[i].name, samples[i].input, &samples[i].expected[pi][rc],
                         pi, rc, pm, host, hf, MAIN_GROUP, false);
            for (size_t i = 0; i < sizeof(rejected)/sizeof(rejected[0]); ++i)
                run_case(rejected[i].name, rejected[i].input, NULL,
                         pi, rc, pm, host, hf, REJECTED_GROUP, false);
            if (host == 0 || host == 3)
                for (size_t i = 0; i < sizeof(focused)/sizeof(focused[0]); ++i) {
                    const sample_t *sample = &samples[focused[i]];
                    run_case(sample->name, sample->input, &sample->expected[pi][rc],
                             pi, rc, pm, host, hf, ALIAS_GROUP, true);
                }
        }
        for (unsigned rc = 0; rc < 4; ++rc)
        for (unsigned pm = 0; pm < 2; ++pm)
        for (size_t i = 0; i < sizeof(focused)/sizeof(focused[0]); ++i) {
            const sample_t *sample = &samples[focused[i]];
            run_case(sample->name, sample->input, &sample->expected[0][rc],
                     0, rc, pm, host, hf, RESERVED_GROUP, false);
        }
        for (unsigned missing = 0; missing < 3; ++missing)
        for (unsigned ci = 0; ci < 4; ++ci)
            run_null(missing, ci, host, hf);
    }
    snprintf(phase, sizeof(phase), "coverage");
    check(calls == PLANNED_CALLS && accepted == PLANNED_ACCEPTED && declined == PLANNED_DECLINED,
          "complete planned call and outcome counts", API);
    check(group_calls[MAIN_GROUP] == 12288 && group_calls[REJECTED_GROUP] == 3072 &&
          group_calls[RESERVED_GROUP] == 512 && group_calls[ALIAS_GROUP] == 768 &&
          group_calls[NULL_GROUP] == 96, "complete planned group coverage", API);
    int result = failures ? 1 : 0;
    printf("x87_finite_sqrt_bridge: calls=%" PRIu64 " accepted=%" PRIu64 " declined=%" PRIu64
           " checks=%" PRIu64 " failures=%" PRIu64 " numeric=%" PRIu64 " api=%" PRIu64
           " host=%" PRIu64 " state=%" PRIu64 " main=%" PRIu64 " rejected=%" PRIu64
           " reserved=%" PRIu64 " alias=%" PRIu64 " null=%" PRIu64 "\n",
           calls, accepted, declined, checks, failures, category_failures[NUMERIC],
           category_failures[API], category_failures[HOST], category_failures[STATE],
           group_calls[MAIN_GROUP], group_calls[REJECTED_GROUP], group_calls[RESERVED_GROUP],
           group_calls[ALIAS_GROUP], group_calls[NULL_GROUP]);
    if (fesetenv(&original) != 0) return 2;
    if (!same_host(caller, host_state())) {
        fprintf(stderr, "Caller floating-point environment restoration failed\n");
        (void)fesetenv(&original);
        return 2;
    }
    return result;
}
