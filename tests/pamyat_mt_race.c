/* MacRunner 2026-08-16, лейн ПАМЯТЬ — МНОГОПОТОЧНОСТЬ СЛОЯ ПАМЯТИ.
 *
 * Зачем. В итоге ступени 7 записано открытым: «многопоточность не проверена ВОВСЕ: все разделы
 * однопоточные, а горячий кеш и поколения — про гонки». Это последний крупный пробел, и он мой.
 *
 * Отдельный файл, а не раздел в `hb_memory_contract_test`: тот стенд намеренно однопоточный и
 * устойчив (145 сверок, 0 нарушений, три прогона подряд). Тащить в него потоки — значит менять
 * прибор, который только что стал годным.
 *
 * Что меряется — две фазы, они проверяют РАЗНОЕ:
 *
 *   Фаза 1. НЕПЕРЕСЕКАЮЩИЕСЯ области. Каждый поток работает со своей: map -> write своего узора
 *           -> read -> сверка. Здесь гонок быть НЕ ДОЛЖНО, и любое расхождение — дефект слоя,
 *           а не игры потоков. Проверяет, что общие структуры (список областей, дерево, горячий
 *           кеш) выдерживают одновременную работу.
 *
 *   Фаза 2. ОДНА область на всех. Пишущий поток гоняет perm r-- <-> rw-, читающие непрерывно
 *           спрашивают предикат и выполняют операцию. Здесь ожидание другое и оно тонкое:
 *           РАСХОЖДЕНИЕ предиката и операции законно (права могли смениться между двумя
 *           вызовами), а НЕЗАКОННЫ только падение хоста и порванное значение — то есть
 *           прочитанное слово, которого никто не писал.
 *
 * Правило 3 входящего (окно должно открыться): проба печатает, сколько РАЗ права реально
 * менялись и сколько операций каждая сторона успела сделать. Если смен нуль или операций мало —
 * фаза 2 ничего не доказывает, и это будет видно числом, а не молчанием.
 *
 * Сборка (цель в общем Makefile — чужая, см. строку НУЖНА ПРАВКА В ЧУЖОМ в прогрессе):
 *   clang -O2 -Wall -std=c11 -I./include -arch arm64 -mmacosx-version-min=14.0 \
 *     -isysroot "$(xcrun --show-sdk-path)" tests/pamyat_mt_race.c libhyperbridge.a \
 *     -o tests/pamyat_mt_race
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <stdlib.h>
#include <pthread.h>
#include <unistd.h>

#include "hb_memory.h"

#define ПОТОКОВ      6
#define КРУГОВ    4000
#define PAGE      0x1000u
#define БАЗА      0x60000000ull

static hb_memory_t *g_mem;
static volatile int g_стоп;

/* Фаза 1: своя область у каждого потока. */
struct своя { int id; unsigned ошибок; unsigned операций; };

static void *поток_свой(void *arg)
{
    struct своя *s = arg;
    hb_gva_t base = БАЗА + (hb_gva_t)s->id * 0x100000ull;
    int k;

    for (k = 0; k < КРУГОВ; k++) {
        uint32_t узор = 0xC0DE0000u | ((uint32_t)s->id << 8) | (uint32_t)(k & 0xff);
        uint32_t назад = 0;

        if (hb_memory_write_u32(g_mem, base + 0x40, узор) != HB_OK) { s->ошибок++; continue; }
        if (hb_memory_read_u32(g_mem, base + 0x40, &назад) != HB_OK) { s->ошибок++; continue; }
        if (назад != узор) s->ошибок++;           /* чужая запись в СВОЮ область — дефект */
        s->операций++;
    }
    return NULL;
}

/* Фаза 2: одна область на всех. */
struct общая { int id; unsigned читал; unsigned отказов; unsigned порвано; unsigned смен; uint32_t образцы[4]; };

static hb_gva_t g_общая;

static void *поток_читатель(void *arg)
{
    struct общая *o = arg;

    while (!g_стоп) {
        uint32_t v = 0;

        if (hb_memory_read_u32(g_mem, g_общая, &v) == HB_OK) {
            o->читал++;
            /* Писатель кладёт только два значения. Любое третье — ПОРВАННОЕ слово. */
            if (v != 0xAAAAAAAAu && v != 0x55555555u) {
                /* ЧТО ИМЕННО прочиталось — без этого «порвано» не отличить от «мусор из
                 * чужого буфера». Первые четыре значения на поток, дальше только счёт. */
                if (o->порвано < 4) o->образцы[o->порвано] = v;
                o->порвано++;
            }
        } else {
            o->отказов++;
        }
    }
    return NULL;
}

static void *поток_писатель(void *arg)
{
    struct общая *o = arg;
    int k;

    for (k = 0; k < КРУГОВ && !g_стоп; k++) {
        hb_perm_t rw = (hb_perm_t)(HB_PERM_READ | HB_PERM_WRITE);

        if (hb_memory_write_u32(g_mem, g_общая, (k & 1) ? 0xAAAAAAAAu : 0x55555555u) == HB_OK)
            o->читал++;
        if (hb_memory_protect(g_mem, g_общая & ~(hb_gva_t)((size_t)getpagesize() - 1),
                              (size_t)getpagesize(), HB_PERM_READ) == HB_OK) o->смен++;
        if (hb_memory_protect(g_mem, g_общая & ~(hb_gva_t)((size_t)getpagesize() - 1),
                              (size_t)getpagesize(), rw) == HB_OK) o->смен++;
    }
    g_стоп = 1;
    return NULL;
}

int main(void)
{
    pthread_t th[ПОТОКОВ];
    struct своя своиx[ПОТОКОВ];
    struct общая общиеx[ПОТОКОВ];
    int i;
    unsigned всего_ошибок = 0, всего_операций = 0;
    unsigned всего_читал = 0, всего_отказов = 0, всего_порвано = 0, всего_смен = 0;
    size_t hp = (size_t)getpagesize();

    setvbuf(stdout, NULL, _IONBF, 0);
    g_mem = hb_memory_create(0);
    if (!g_mem) { printf("ОТКАЗ ОСНАСТКИ: hb_memory_create вернул NULL\n"); return 2; }

    printf("проба многопоточности слоя памяти: потоков %d, кругов %d, хостовая страница %zu Б\n",
           ПОТОКОВ, КРУГОВ, hp);

    /* --- Фаза 1: неперекрывающиеся области ------------------------------------------------ */
    for (i = 0; i < ПОТОКОВ; i++) {
        hb_gva_t base = БАЗА + (hb_gva_t)i * 0x100000ull;

        if (hb_memory_map_private(g_mem, base, hp,
                                  (hb_perm_t)(HB_PERM_READ | HB_PERM_WRITE)) != HB_OK) {
            printf("  ПРОПУСК: область %d не отобразилась\n", i);
            return 2;
        }
        своиx[i].id = i; своиx[i].ошибок = 0; своиx[i].операций = 0;
    }
    for (i = 0; i < ПОТОКОВ; i++) pthread_create(&th[i], NULL, поток_свой, &своиx[i]);
    for (i = 0; i < ПОТОКОВ; i++) pthread_join(th[i], NULL);
    for (i = 0; i < ПОТОКОВ; i++) { всего_ошибок += своиx[i].ошибок; всего_операций += своиx[i].операций; }
    printf("  фаза 1 (свои области): операций %u, РАСХОЖДЕНИЙ %u\n", всего_операций, всего_ошибок);

    /* --- Фаза 2: одна область на всех ------------------------------------------------------ */
    g_общая = БАЗА + 0x900000ull;
    if (hb_memory_map_private(g_mem, g_общая, hp,
                              (hb_perm_t)(HB_PERM_READ | HB_PERM_WRITE)) != HB_OK) {
        printf("  ПРОПУСК: общая область не отобразилась\n");
    } else {
        hb_memory_write_u32(g_mem, g_общая, 0x55555555u);
        memset(общиеx, 0, sizeof(общиеx));
        g_стоп = 0;
        for (i = 0; i < ПОТОКОВ; i++) общиеx[i].id = i;
        pthread_create(&th[0], NULL, поток_писатель, &общиеx[0]);
        for (i = 1; i < ПОТОКОВ; i++) pthread_create(&th[i], NULL, поток_читатель, &общиеx[i]);
        for (i = 0; i < ПОТОКОВ; i++) pthread_join(th[i], NULL);
        for (i = 0; i < ПОТОКОВ; i++) {
            всего_читал += общиеx[i].читал; всего_отказов += общиеx[i].отказов;
            всего_порвано += общиеx[i].порвано; всего_смен += общиеx[i].смен;
        }
        printf("  фаза 2 (одна область): успешных чтений %u, отказов %u, СМЕН ПРАВ %u, ПОРВАНО %u\n",
               всего_читал, всего_отказов, всего_смен, всего_порвано);
        for (i = 0; i < ПОТОКОВ; i++) {
            unsigned j;
            for (j = 0; j < 4 && j < общиеx[i].порвано; j++)
                printf("    порванное значение: поток %d -> %08x\n", i, общиеx[i].образцы[j]);
        }
        if (!всего_смен)
            printf("  ★ ФАЗА 2 НИЧЕГО НЕ ДОКАЗЫВАЕТ: смен прав ноль, окно не открылось\n");
    }

    hb_memory_destroy(g_mem);
    printf("итог: расхождений в своих областях %u, порванных слов %u\n",
           всего_ошибок, всего_порвано);
    return (всего_ошибок || всего_порвано) ? 1 : 0;
}
